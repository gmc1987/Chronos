-- 为学生建立公共基础课教学班成员关系，支撑学生及行政班课表查询。
-- 主键由学生和教学任务的稳定业务组合计算，重复执行不会制造新记录。
INSERT INTO edu_teaching_class_member (
    id, offering_id, student_id, enrollment_status, enrolled_at,
    create_by, create_time, last_update_by, last_update_time
)
SELECT
    substring(member_hash, 1, 8) || '-' ||
    substring(member_hash, 9, 4) || '-4' ||
    substring(member_hash, 14, 3) || '-8' ||
    substring(member_hash, 18, 3) || '-' ||
    substring(member_hash, 21, 12),
    offering_id,
    student_id,
    'ENROLLED',
    CURRENT_TIMESTAMP,
    'SYSTEM',
    CURRENT_TIMESTAMP,
    'SYSTEM',
    CURRENT_TIMESTAMP
FROM (
    SELECT
        md5(student.id || ':' || offering.id) AS member_hash,
        offering.id AS offering_id,
        student.id AS student_id
    FROM edu_student_profile student
    CROSS JOIN edu_course_offering offering
    WHERE student.enrollment_status = 'ACTIVE'
      AND offering.semester_code = '2026-2027-1'
      AND offering.offering_code IN (
          'GG-YW-001',
          'GG-SX-001',
          'GG-YY-001',
          'GG-ZY-001'
      )
) member_seed
ON CONFLICT (offering_id, student_id) DO NOTHING;

